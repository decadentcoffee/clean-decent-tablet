#!/usr/bin/env python3
"""Write docs/packages.md from manifests/packages.csv. Run after any manifest change."""

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
with (ROOT / "manifests/packages.csv").open() as f:
    rows = list(csv.DictReader(f))

BATCHES = {
    "1": "Consumer apps",
    "2": "Linking, sharing and companion features",
    "3": "Samsung Internet",
    "4": "Samsung data and promotion agents",
    "5": "Riskier agents",
    "6": "Leftovers",
    "8": "Requested later",
    "9": "Requested after One UI 8.5",
}
DECENT = ["tk.tcl.wish", "hu.kavekalmar.sep", "com.pressensor.coffeeflow", "com.alphainventor.filemanager", "com.hecorat.screenrecorder.free"]
ADDED = ["net.tadel.reaprime", "org.fossify.home", "app.olauncher", "org.chromium.webapk.a45977050c6c6f69b_v2"]
by = {r["package"]: r for r in rows}


def clean(s):
    return s.replace("|", "/").strip()


def table(items):
    out = ["| Package | Name | Why |", "|---|---|---|"]
    out += [f"| `{r['package']}` | {clean(r['name'])} | {clean(r['reason'])} |" for r in items]
    return out


disabled = [r for r in rows if r["proposed_action"] == "disable" and r["approval"] == "approved"]
original = [r for r in rows if r["original_state"] == "disabled"]
refused = [r for r in rows if "refuses" in r["reason"]]
named = [r for r in rows if r["category"] == "KEEP" and r["name"] and r["package"] not in DECENT + ADDED and r["original_state"] != "disabled"]
unreviewed = sum(1 for r in rows if r["category"] == "KEEP" and not r["name"] and r["original_state"] != "disabled")

doc = [
    "# Every package on the reference tablet",
    "",
    "Generated by `scripts/render-packages.py` from `manifests/packages.csv`. Do not edit by hand.",
    "Applies to SM-X133 / X133DXS4BZB6. Names come from package identifiers and the app list, because Android does not print labels over ADB.",
    "",
    f"**Totals:** {len(rows)} packages. {len(disabled)} disabled by this project, {len(original)} already disabled by Decent, {len(rows) - len(disabled) - len(original)} enabled.",
    "",
    "## Shipped by Decent: all enabled",
    "",
    "Installed together on 16 Feb 2026 on the reference tablet. The Home-screen icons **Decent** and **Update Decent** are shortcuts into AndroWish.",
    "",
    *table([by[p] for p in DECENT]),
    "",
    "## Added for this setup",
    "",
    *table([by[p] for p in ADDED]),
    "",
    "## Already disabled by Decent: leave disabled",
    "",
    *table(original),
    "",
    f"## Disabled by this project: {len(disabled)}",
    "",
]
for b, title in BATCHES.items():
    items = [r for r in disabled if r["batch"] == b]
    doc += [f"### Batch {b}: {title} ({len(items)})", "", *table(items), ""]
doc += [
    "## Android refuses to disable these",
    "",
    *table(refused),
    "",
    "## Kept on purpose",
    "",
    *table([r for r in named if r not in refused]),
    "",
    f"The other {unreviewed} enabled packages are Android and Samsung system components, not reviewed for removal. The full list is in `manifests/packages.csv`.",
    "",
]
(ROOT / "docs/packages.md").write_text("\n".join(doc))
plan = ["# batch package. Generated from manifests/packages.csv by scripts/render-packages.py. Do not edit by hand."]
plan += [f"{r['batch']} {r['package']}" for r in sorted(disabled, key=lambda r: (int(r["batch"]), r["package"]))]
(ROOT / "device/packages-disable.txt").write_text("\n".join(plan) + "\n")
expect = (ROOT / "manifests/device.expect").read_text()
(ROOT / "device/device.expect").write_text(expect)
# README: every disabled app and why, in plain words, between markers.
PUBLIC_WHY = {
    "com.google.android.apps.bard": "AI assistant added by One UI 8.5; not needed on an espresso controller",
    "com.samsung.android.app.contacts": "No calls or contacts on a Wi-Fi tablet",
    "com.sec.android.app.myfiles": "Samsung's file manager. File Manager +, which Decent ships, stays",
    "com.sec.android.app.sbrowser": "Samsung's browser. Chrome becomes the browser instead",
    "com.sec.spp.push": "Samsung notifications. Firmware updates still arrive with it off (tested)",
    "com.sec.android.app.samsungapps": "Samsung's app store. Updates to Samsung's own apps through it stop",
    "com.samsung.android.intellivoiceservice": "Samsung voice wake-up (purpose inferred from its name)",
    "com.samsung.android.forest": "Screen-time tracking; not needed here",
    "com.google.android.googlequicksearchbox": "Google app: Discover, OK Google and Circle to Search. Chrome still works",
    "com.sec.android.autodoodle.service": "Photo editor add-on. Not present on One UI 8.5",
}
GROUPS = [
    ("📺", "Consumer apps", ["1"]),
    ("🔗", "Sharing, linking and companion features", ["2"]),
    ("🔁", "Replaced or not needed", ["3", "8", "9"]),
    ("📡", "Samsung data collection and promotion agents", ["4"]),
    ("⚙️", "Samsung services with wider effects", ["5"]),
    ("🧹", "Small background services", ["6"]),
]
readme = ROOT / "README.md"
if readme.exists():
    rd = readme.read_text()
    start, end = "<!-- disabled-apps:start -->", "<!-- disabled-apps:end -->"
    if start in rd and end in rd:
        body = [start, "<!-- Generated by scripts/render-packages.py from manifests/packages.csv. Do not edit by hand. -->", "",
                "| | Group | Apps |", "|---|---|---|"]
        for icon, title, batches in GROUPS:
            items = [r for r in disabled if r["batch"] in batches]
            names = ", ".join(clean(r["name"]) for r in items[:4]) + (", …" if len(items) > 4 else "")
            body.append(f"| {icon} | **{title}** ({len(items)}) | {names} |")
        body.append("")
        for icon, title, batches in GROUPS:
            items = sorted([r for r in disabled if r["batch"] in batches], key=lambda r: r["name"].lower())
            body += [f"<details><summary>{icon} <b>{title}</b>: {len(items)} apps</summary>", "",
                     "| App | Package | Why it is disabled |", "|---|---|---|"]
            body += [f"| {clean(r['name'])} | `{r['package']}` | {clean(PUBLIC_WHY.get(r['package'], r['reason']))} |" for r in items]
            body += ["", "</details>", ""]
        body.append(end)
        i, j = rd.index(start), rd.index(end) + len(end)
        readme.write_text(rd[:i] + "\n".join(body) + rd[j:])
# The webpage's per-app choices: same groups and wording as the README.
import json
apps = []
for icon, title, batches in GROUPS:
    for r in sorted([r for r in disabled if r["batch"] in batches], key=lambda r: r["name"].lower()):
        apps.append({"group": title, "pkg": r["package"], "batch": r["batch"], "name": clean(r["name"]), "why": clean(PUBLIC_WHY.get(r["package"], r["reason"]))})
(ROOT / "web/src/apps.json").write_text(json.dumps(apps, indent=1, ensure_ascii=False) + "\n")
print("disabled", len(disabled), "original", len(original), "refused", len(refused), "named keeps", len(named), "unreviewed", unreviewed)
